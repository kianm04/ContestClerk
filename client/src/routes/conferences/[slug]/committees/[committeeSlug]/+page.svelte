<script lang="ts">
	import BookOpen from '@lucide/svelte/icons/book-open';
	import ListOrdered from '@lucide/svelte/icons/list-ordered';
	import { committeeHeading } from '$lib/committees';
	import Badge from '$lib/components/Badge.svelte';
	import Card from '$lib/components/Card.svelte';
	import Flag from '$lib/components/Flag.svelte';
	import Notice from '$lib/components/Notice.svelte';
	import ParagraphText from '$lib/components/ParagraphText.svelte';
	import Section from '$lib/components/Section.svelte';
	import PageMeta from '$lib/components/shell/PageMeta.svelte';
	import { paperStatusLabel } from '$lib/documents';
	import { paperStatusTone } from '$lib/documents-page';
	import { conferenceUrl } from '$lib/urls';
	import type { PageProps } from './$types';
	import CommitteeAwardsCard from './CommitteeAwardsCard.svelte';
	import CommitteeGuideCard from './CommitteeGuideCard.svelte';
	import CommitteeHeader from './CommitteeHeader.svelte';
	import CommitteeResolutions from './CommitteeResolutions.svelte';
	import CommitteeRoleLinks from './CommitteeRoleLinks.svelte';
	import SeatGrid from './SeatGrid.svelte';

	// `PageProps` comes from `./$types`, generated by SvelteKit from this route's own
	// `load`, so `data` is exactly what `+page.server.ts` returned for this address.
	let { data }: PageProps = $props();

	// `$derived` works both of these out again whenever `data` changes. `mySeat` is
	// `undefined` when the reader holds no seat in this committee.
	const shareDescription = $derived(
		data.committee.description ?? `${data.committee.name} at ${data.conference.name}.`
	);
	const mySeat = $derived(data.seats.find((seat) => seat.id === data.viewer.mySeatId));
</script>

<!-- `PageMeta` adds " · MUNMeet", so the tab reads "UNSC · Amsterdam Open MUN · MUNMeet". -->
<PageMeta
	title="{committeeHeading(data.committee)} · {data.conference.name}"
	description={shareDescription}
	imageUrl={data.shareImageUrl}
/>

<div class="flex flex-col gap-6">
	{#if data.conference.status === 'draft'}
		<Notice tone="warning" title="Draft preview">Only your team can see this page.</Notice>
	{/if}

	<a href={conferenceUrl(data.conference.slug)} class="text-small text-brand-700 hover:underline">
		‹ {data.conference.name}
	</a>

	<CommitteeHeader
		committee={data.committee}
		chairs={data.chairs}
		seatCount={data.seats.length}
		isSignedIn={data.isSignedIn}
	/>

	<CommitteeRoleLinks
		conferenceSlug={data.conference.slug}
		committeeId={data.committee.id}
		committeeSlug={data.committee.slug}
		papersTitle={data.papersTitle}
		mySeatId={data.viewer.mySeatId}
		positionPaperRequired={data.conference.positionPaperRequired}
		myPaperStatus={data.viewer.myPaperStatus}
		isChair={data.viewer.isChair}
		canManage={data.viewer.canManage}
		isCrisisStaff={data.isCrisisStaff}
	/>

	<div class="grid gap-8 lg:grid-cols-[minmax(0,1fr)_20rem]">
		<div class="flex flex-col gap-6">
			<Section title="Topics" icon={ListOrdered}>
				{#if data.committee.topics.length === 0}
					<p class="text-body text-ink-600">Topics to be announced.</p>
				{:else}
					<ol class="list-inside list-decimal text-body">
						<!-- Topics have no id of their own, and two of them can read the same, so
							the place in the list is the key rather than the words. -->
						{#each data.committee.topics as topic, index (index)}
							<li>{topic}</li>
						{/each}
					</ol>
				{/if}
			</Section>

			{#if data.committee.description}
				<Section title="About" icon={BookOpen}>
					<ParagraphText text={data.committee.description} />
				</Section>
			{/if}

			<CommitteeResolutions title={data.papersTitle} resolutions={data.resolutions} />

			<SeatGrid
				seats={data.seats}
				mySeatId={data.viewer.mySeatId}
				canSeeSeatHolders={data.viewer.canSeeSeatHolders}
			/>
		</div>

		<!-- `lg:self-start` stops the column stretching, so `lg:sticky` can hold it in view. -->
		<div class="flex flex-col gap-6 lg:sticky lg:top-20 lg:self-start">
			<CommitteeGuideCard guide={data.backgroundGuide} isInsider={data.viewer.canSeeSeatHolders} />
			{#if mySeat}
				<Card>
					<h2 class="font-display text-h2 text-brand-900">Your seat</h2>
					<p class="mt-2 flex items-center gap-2 text-body">
						{#if mySeat.countryCode}
							<Flag countryCode={mySeat.countryCode} />
						{/if}
						{mySeat.name}
					</p>
					{#if data.viewer.myPaperStatus}
						<div class="mt-2">
							<Badge
								tone={paperStatusTone(data.viewer.myPaperStatus)}
								label={paperStatusLabel(data.viewer.myPaperStatus)}
							/>
						</div>
					{/if}
				</Card>
			{/if}
			<!-- Nothing is drawn while there are no awards this reader may see. -->
			{#if data.awards.length > 0}
				<CommitteeAwardsCard awards={data.awards} isPublished={data.awardsPublishedAt !== null} />
			{/if}
		</div>
	</div>
</div>
